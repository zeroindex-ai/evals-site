import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { escapeHtml, parseArgs, redactAnswerText, wrapWithSiteShell } from './render.ts';

// ─── wrapWithSiteShell ──────────────────────────────────────────────────────

// Mirrors @zeroindex-ai/eval-pack's renderHtml() shape: a flat sequence of
// <header>/<section>/<details> nodes inside <body>, plus a trailing <footer>
// the site shell strips. No nested <main> — that's the wrapper's job.
const RAW_EVAL_PACK_HTML = `<!DOCTYPE html>
<html><head><title>eval-pack default</title><style>/* eval-pack styles */</style></head>
<body>
  <header><h1>ask-zeroindex</h1></header>
  <section><h2>Summary</h2><div class="pass-rate ok">93%</div></section>
  <details><summary class="pass">case 1</summary><div class="body">ok</div></details>
  <footer>Generated by @zeroindex-ai/eval-pack</footer>
</body></html>`;

describe('wrapWithSiteShell', () => {
  it('wraps raw eval-pack output and emits the ZeroIndex site shell', () => {
    const out = wrapWithSiteShell(RAW_EVAL_PACK_HTML, 'ask-zeroindex');

    // Document chrome
    expect(out.startsWith('<!DOCTYPE html>')).toBe(true);
    expect(out).toContain('<html lang="en">');
    expect(out).toContain('<title>ask-zeroindex eval results · ZeroIndex</title>');

    // ZeroIndex shell elements present
    expect(out).toContain('class="site-header"');
    expect(out).toContain('class="report-shell"');
    expect(out).toContain('<div class="label">Eval Report</div>');
    expect(out).toContain('&copy; 2026 ZeroIndex LLC');

    // Shared asset wiring (no Tailwind CDN script, brand mark inline, fonts via Google Fonts)
    expect(out).toContain('<link rel="stylesheet" href="/styles/zeroindex.css"');
    expect(out).toContain('viewBox="4 0 24 32"');
    expect(out).toContain('fonts.googleapis.com/css2?family=Inter');
    expect(out).not.toContain('cdn.tailwindcss.com');
    expect(out).not.toMatch(/<script\b[^>]*\bsrc=/);

    // Refreshed header chrome: CTA-pill back link + permanent inset border,
    // and the old scroll-toggle script is gone (border is always on).
    expect(out).toContain('class="btn-primary"');
    expect(out).toContain('border-b line');
    expect(out).not.toContain('siteHeader');
    expect(out).not.toContain('window.scrollY');

    // Body kept; eval-pack's inner <footer> stripped
    expect(out).toContain('<h1>ask-zeroindex</h1>');
    expect(out).toContain('<div class="pass-rate ok">93%</div>');
    expect(out).not.toContain('Generated by @zeroindex-ai/eval-pack');
  });

  it('is idempotent: rewrapping an already-wrapped page yields the same output', () => {
    const once = wrapWithSiteShell(RAW_EVAL_PACK_HTML, 'ask-zeroindex');
    const twice = wrapWithSiteShell(once, 'ask-zeroindex');
    expect(twice).toBe(once);

    // And we never produce nested report-shells.
    const shellOpens = (twice.match(/<main\b[^>]*report-shell/g) ?? []).length;
    expect(shellOpens).toBe(1);

    // The "Eval Report" kicker appears exactly once, not stacked.
    const kickers = (twice.match(/<div class="label">Eval Report<\/div>/g) ?? []).length;
    expect(kickers).toBe(1);
  });

  it('escapes HTML special characters in the project name', () => {
    const out = wrapWithSiteShell('<p>hi</p>', '<script>alert(1)</script>');
    expect(out).toContain('&lt;script&gt;alert(1)&lt;/script&gt;');
    expect(out).not.toContain('<script>alert(1)</script>');
    // The title and meta description both echo the project name and must both
    // be safely escaped, not just one of them.
    expect(out).toMatch(/<title>&lt;script&gt;[^<]*<\/title>/);
    expect(out).toMatch(/content="Live eval report for &lt;script&gt;/);
  });

  // Guards the <head> against silent regressions: every required favicon link,
  // the Google-Fonts preconnect + stylesheet, and the pre-built site CSS must be
  // present. evals-site ships a static stylesheet (no JIT at deploy), so a
  // dropped <link> would break the page with no error anywhere.
  it('emits the required <head> tags (favicons, fonts, site CSS)', () => {
    const out = wrapWithSiteShell(RAW_EVAL_PACK_HTML, 'ask-zeroindex');
    const head = out.slice(out.indexOf('<head>'), out.indexOf('</head>'));

    // 5-file favicon set
    expect(head).toContain('<link rel="icon" href="/favicon.ico" sizes="any" />');
    expect(head).toContain('<link rel="icon" type="image/svg+xml" href="/favicon.svg" />');
    expect(head).toContain('<link rel="icon" type="image/png" sizes="48x48" href="/favicon-48x48.png" />');
    expect(head).toContain('<link rel="icon" type="image/png" sizes="96x96" href="/favicon-96x96.png" />');
    expect(head).toContain('<link rel="apple-touch-icon" href="/favicon-180x180.png" />');

    // Google-Fonts preconnect pair + the stylesheet link
    expect(head).toContain('<link rel="preconnect" href="https://fonts.googleapis.com" />');
    expect(head).toContain('<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />');
    expect(head).toContain(
      '<link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700;800&family=JetBrains+Mono:wght@400;500&display=swap" rel="stylesheet" />'
    );

    // The pre-built ZeroIndex site stylesheet
    expect(head).toContain('<link rel="stylesheet" href="/styles/zeroindex.css" />');
  });
});

// ─── escapeHtml ─────────────────────────────────────────────────────────────

describe('escapeHtml', () => {
  it('escapes the five HTML-sensitive characters', () => {
    expect(escapeHtml(`<a href="x" onclick='y'>&</a>`)).toBe(
      '&lt;a href=&quot;x&quot; onclick=&#39;y&#39;&gt;&amp;&lt;/a&gt;'
    );
  });

  it('leaves a plain string unchanged', () => {
    expect(escapeHtml('ask-zeroindex')).toBe('ask-zeroindex');
  });
});

// ─── parseArgs ──────────────────────────────────────────────────────────────

describe('parseArgs', () => {
  it('parses a complete argument set', () => {
    const args = parseArgs([
      '--in',
      'artifacts/run.json',
      '--out',
      'public/foo/latest.html',
      '--project',
      'foo',
      '--threshold',
      '0.8',
    ]);
    expect(args).toEqual({
      in: 'artifacts/run.json',
      out: 'public/foo/latest.html',
      project: 'foo',
      threshold: 0.8,
    });
  });

  it('makes --threshold optional', () => {
    const args = parseArgs(['--in', 'a.json', '--out', 'b.html', '--project', 'p']);
    expect(args.threshold).toBeUndefined();
  });

  it('rejects a non-numeric --threshold value', () => {
    expect(() =>
      parseArgs(['--in', 'a.json', '--out', 'b.html', '--project', 'p', '--threshold', 'abc'])
    ).toThrow(/threshold/i);
  });

  it('rejects a --threshold without a value (next token is another flag)', () => {
    expect(() => parseArgs(['--threshold', '--project', 'p'])).toThrow(/missing value for --threshold/i);
  });

  it('rejects a flag with a missing value at the end of argv', () => {
    expect(() => parseArgs(['--in'])).toThrow(/missing value for --in/i);
  });

  it('rejects unknown flags', () => {
    expect(() => parseArgs(['--bogus', 'x'])).toThrow(/unknown flag/i);
  });

  it('parses the valueless --redact-answers flag', () => {
    const args = parseArgs(['--in', 'a.json', '--out', 'b.html', '--project', 'p', '--redact-answers']);
    expect(args.redactAnswers).toBe(true);
    // does not consume the following token as a value
    expect(args.project).toBe('p');
  });

  it('leaves redactAnswers undefined when the flag is absent', () => {
    const args = parseArgs(['--in', 'a.json', '--out', 'b.html', '--project', 'p']);
    expect(args.redactAnswers).toBeUndefined();
  });
});

// ─── redactAnswerText ─────────────────────────────────────────────────────────

// Mirrors eval-pack's item shape: the "Answer text:" label div immediately
// followed by a <div class="text"> holding the (escaped) model output.
const ITEM_WITH_ANSWER =
  '<div class="field"><span class="field-label">Question:</span> hi</div>' +
  '<div class="field"><span class="field-label">Answer text:</span></div>' +
  '<div class="text">Dear founder, you&#39;re asking about a RAG build. Regards.</div>' +
  '<div class="field"><span class="field-label">Total ms:</span> <code>1200</code></div>';

describe('redactAnswerText', () => {
  it('removes the answer body but keeps the label and surrounding fields', () => {
    const out = redactAnswerText(ITEM_WITH_ANSWER);
    expect(out).not.toContain('class="text"');
    expect(out).not.toContain('you&#39;re asking about');
    expect(out).toContain('Answer text:');
    expect(out).toContain('withheld (internal)');
    // unrelated fields survive
    expect(out).toContain('Question:');
    expect(out).toContain('Total ms:');
  });

  it('is idempotent (already-redacted input is unchanged)', () => {
    const once = redactAnswerText(ITEM_WITH_ANSWER);
    expect(redactAnswerText(once)).toBe(once);
  });

  it('only redacts when wrapWithSiteShell is told to', () => {
    const body = `<body><main class="report-shell">${ITEM_WITH_ANSWER}</main></body>`;
    expect(wrapWithSiteShell(body, 'intake-zero')).toContain('class="text"');
    expect(wrapWithSiteShell(body, 'intake-zero', { redactAnswers: true })).not.toContain('class="text"');
  });
});

// ─── main() CLI round-trip ────────────────────────────────────────────────────

// Exercises the full CLI path: a RunReport JSON on disk → `tsx render.ts` →
// a wrapped HTML file on disk. Spawns the script as a subprocess (the real
// entrypoint) so process.argv parsing, file I/O, mkdir, and eval-pack's
// renderHtml all run end-to-end, then asserts the output exists and carries the
// expected markers. Mirrors a minimal @zeroindex-ai/eval-pack RunReport shape.
describe('main() round-trip', () => {
  const repoRoot = dirname(fileURLToPath(import.meta.url));
  let tmp: string;

  const REPORT = {
    ran: '2026-05-25T00:00:00.000Z',
    results: [
      {
        id: 'q1',
        category: 'smoke',
        question: 'What does ZeroIndex do?',
        text: 'It publishes eval reports.',
        retrievedRefs: [],
        citationRefs: [],
        recallAtK: null,
        timings: { totalMs: 1200 },
        metadata: {},
        checks: [],
        judgment: null,
        pass: true,
      },
    ],
    errors: [],
  };

  beforeAll(() => {
    tmp = mkdtempSync(join(tmpdir(), 'evals-site-roundtrip-'));
  });

  afterAll(() => {
    rmSync(tmp, { recursive: true, force: true });
  });

  it('writes a wrapped HTML report from a JSON input', () => {
    const inPath = join(tmp, 'run.json');
    const outPath = join(tmp, 'nested', 'latest.html'); // nested dir tests mkdir
    writeFileSync(inPath, JSON.stringify(REPORT));

    const stdout = execFileSync(
      'pnpm',
      ['render', '--in', inPath, '--out', outPath, '--project', 'round-trip-demo'],
      { cwd: repoRoot, encoding: 'utf-8' }
    );

    expect(stdout).toContain('1/1 passed (100%)');
    expect(existsSync(outPath)).toBe(true);

    const html = readFileSync(outPath, 'utf-8');
    expect(html.startsWith('<!DOCTYPE html>')).toBe(true);
    expect(html).toContain('<title>round-trip-demo eval results · ZeroIndex</title>');
    expect(html).toContain('class="report-shell"');
    expect(html).toContain('<div class="label">Eval Report</div>');
    expect(html).toContain('What does ZeroIndex do?');
    expect(html).toContain('<link rel="stylesheet" href="/styles/zeroindex.css" />');
  });
});
