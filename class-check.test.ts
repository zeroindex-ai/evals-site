// No-JIT class-check (guards the build:css footgun).
//
// evals-site ships a *pre-built* static stylesheet (public/styles/zeroindex.css,
// produced by `pnpm build:css`). Tailwind v4 only emits a rule for a utility
// class it actually saw while scanning the @source globs. So any class token
// referenced in render.ts's emitted HTML or in a public/**/*.html page that has
// NO matching rule in the built CSS ships *silently broken* — the markup renders
// unstyled in production with no error anywhere.
//
// This test makes that failure loud: it rebuilds the CSS from the current source
// (so the check is deterministic and never trusts a possibly-stale committed
// file), collects every class token actually referenced, and asserts each one
// resolves to a rule in the built stylesheet.

import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { readdirSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dirname } from 'node:path';
import { beforeAll, describe, expect, it } from 'vitest';
import { wrapWithSiteShell } from './render.ts';

const repoRoot = dirname(fileURLToPath(import.meta.url));
const CSS_PATH = join(repoRoot, 'public', 'styles', 'zeroindex.css');
const PUBLIC_DIR = join(repoRoot, 'public');

// A representative @zeroindex-ai/eval-pack body. render.ts wraps this; the
// wrapper's own chrome classes (skip-link, site-header, btn-primary,
// report-shell, the footer utilities, …) only appear in its output, so we must
// exercise the wrapper to capture them — scanning public/**/*.html alone would
// miss any class the shell emits that no current report page happens to use.
const SAMPLE_EVAL_PACK_BODY = `<!DOCTYPE html>
<html><head><title>t</title></head>
<body>
  <header><h1>sample</h1><div class="meta"><span>n=3</span></div></header>
  <section><h2>Summary</h2><div class="pass-rate ok">93%</div></section>
  <details><summary class="pass">case 1</summary><div class="body">
    <div class="field"><span class="field-label">Answer text:</span></div>
    <div class="text">ok</div>
    <span class="tag ok">ok</span>
  </div></details>
  <footer>Generated by @zeroindex-ai/eval-pack</footer>
</body></html>`;

/** Every distinct class token referenced inside a chunk of HTML. */
function classTokensIn(html: string): Set<string> {
  const tokens = new Set<string>();
  for (const m of html.matchAll(/\bclass="([^"]*)"/g)) {
    for (const t of (m[1] ?? '').split(/\s+/)) {
      if (t) tokens.add(t);
    }
  }
  return tokens;
}

/** Recursively list every *.html under public/. */
function publicHtmlFiles(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...publicHtmlFiles(full));
    } else if (entry.isFile() && entry.name.endsWith('.html')) {
      out.push(full);
    }
  }
  return out;
}

// Tailwind escapes selector-special characters in the generated class selector
// (e.g. `md:px-10` -> `.md\:px-10`, `text-[15px]` -> `.text-\[15px\]`). Mirror
// that escaping so we look for the exact selector text the build emits.
const SELECTOR_SPECIAL = new Set('.:/[](),%#!+~>*&'.split(''));
function escapeForSelector(token: string): string {
  let out = '';
  for (const ch of token) out += SELECTOR_SPECIAL.has(ch) ? '\\' + ch : ch;
  return out;
}

const SELECTOR_CONTINUATION = /[A-Za-z0-9_-]/;

/**
 * True if `token` has a corresponding class rule (or compound selector) in the
 * built CSS. Matches `.<escaped-token>` only when it is NOT followed by another
 * class-name character, so `gap-3` does not spuriously match inside `.gap-32`.
 */
function hasRule(css: string, token: string): boolean {
  const needle = '.' + escapeForSelector(token);
  let from = 0;
  for (;;) {
    const idx = css.indexOf(needle, from);
    if (idx === -1) return false;
    const after = css[idx + needle.length] ?? '';
    if (!SELECTOR_CONTINUATION.test(after)) return true;
    from = idx + 1;
  }
}

let builtCss = '';
let referenced: string[] = [];

beforeAll(() => {
  // Rebuild from current source so the check is deterministic and never relies
  // on a stale committed stylesheet.
  execFileSync('pnpm', ['build:css'], { cwd: repoRoot, stdio: 'pipe' });
  builtCss = readFileSync(CSS_PATH, 'utf-8');

  const tokens = new Set<string>();
  // (a) classes emitted by render.ts's site shell
  for (const t of classTokensIn(wrapWithSiteShell(SAMPLE_EVAL_PACK_BODY, 'sample'))) {
    tokens.add(t);
  }
  // (b) classes in every published page
  for (const file of publicHtmlFiles(PUBLIC_DIR)) {
    for (const t of classTokensIn(readFileSync(file, 'utf-8'))) tokens.add(t);
  }
  referenced = [...tokens].sort();
});

describe('no-JIT class-check', () => {
  it('finds class tokens to check (sanity guard)', () => {
    expect(referenced.length).toBeGreaterThan(20);
  });

  it('every referenced class has a rule in the built stylesheet', () => {
    const missing = referenced.filter((t) => !hasRule(builtCss, t));
    expect(
      missing,
      `These classes are referenced in render.ts output or public/**/*.html but have ` +
        `no rule in public/styles/zeroindex.css. Tailwind only emits classes it sees ` +
        `via the @source globs in src/styles/input.css — add/restore the @source entry ` +
        `or fix the class name, then re-run \`pnpm build:css\`.\n  ${missing.join('\n  ')}`
    ).toEqual([]);
  });

  it('the check would bite: a bogus class is reported missing', () => {
    // Proves the guard actually detects an unstyled class (and that the
    // prefix-boundary logic doesn't accidentally match a real rule).
    expect(hasRule(builtCss, 'totally-bogus-class-xyz')).toBe(false);
    // And a real one is still found, so the assertion above isn't vacuous.
    expect(hasRule(builtCss, 'report-shell')).toBe(true);
  });
});
